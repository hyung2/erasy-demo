// 위험 알림 모달을 띄울지 판단한다.
//
// 모달은 사용자의 흐름을 끊는 개입이다. 개입을 정당화하려면 "위험이 있다"가 아니라
// **"지금 봐야 할 만큼 많다"**여야 한다. 이전에는 위험 계정이 1개만 있어도 떴는데,
// 한둘은 목록에서 배지로 이미 보이므로 화면을 덮을 이유가 없다.
// (0건일 때 뜨던 것은 2026-08-18에 고쳤고, "있으면 뜬다"에서 멈춰 있었다.)
//
// 페이지가 아니라 여기 두는 이유: 임계값은 검증 대상이고, 라우트 파일에서 로직을
// 내보내면 다음 사람이 그걸 찾지 못한다.

/** 손으로 훑기 벅찬 양. 서너 개는 스크롤로 처리된다. */
const RISK_ALERT_MIN_COUNT = 10;

/** 전체에서 차지하는 몫. 265개 중 20개(8%)는 사소하고, 20개 중 12개(60%)는 심각하다. */
const RISK_ALERT_MIN_RATIO = 0.2;

/**
 * 위험 계정이 모달로 알릴 만큼 많은가.
 *
 * 개수와 비율을 **함께** 본다. 하나만 쓰면 한쪽이 무너진다 — 개수만 보면 계정이 많은
 * 사람이 늘 걸리고, 비율만 보면 계정 3개 중 2개인 사람에게 모달이 뜬다.
 */
export function shouldAlertRisk(highRisk: number, total: number): boolean {
  if (total <= 0) return false;
  return highRisk >= RISK_ALERT_MIN_COUNT && highRisk / total >= RISK_ALERT_MIN_RATIO;
}
